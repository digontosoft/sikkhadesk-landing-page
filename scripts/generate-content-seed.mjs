import { readFile, writeFile, mkdir } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import ts from "typescript"

const root = new URL("../", import.meta.url)

// These two starter files contain data and erased type-only imports.
async function readConstant(relativePath, name) {
  const source = await readFile(new URL(relativePath, root), "utf8")
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
    },
  })
  const starterExports = await import(
    `data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`
  )
  return starterExports[name]
}

const [modules, about] = await Promise.all([
  readConstant("constants/modules.ts", "productModules"),
  readConstant("constants/about.ts", "aboutContent"),
])

function literal(value) {
  return `'${String(value).replaceAll("'", "''")}'`
}

const inserts = modules.map(
  ({ slug, ...content }, index) =>
    `insert into public.landing_modules (slug, content, is_published, sort_order) values (${literal(slug)}, ${literal(JSON.stringify(content))}::jsonb, true, ${index}) on conflict (slug) do nothing;`
)
inserts.push(
  `insert into public.landing_pages (slug, content, is_published, sort_order) values ('about', ${literal(JSON.stringify(about))}::jsonb, true, 0) on conflict (slug) do nothing;`
)

await mkdir(new URL("supabase/", root), { recursive: true })
const destination = new URL("supabase/seed.sql", root)
await writeFile(
  destination,
  [
    "-- Generated by npm run content:seed. Run after the schema migration.",
    "-- Existing rows are preserved. Example tables are explicitly fictional.",
    "-- This file makes no network requests and does not modify a live database.",
    "begin;",
    ...inserts,
    "commit;",
    "",
  ].join("\n"),
  "utf8"
)
console.log(
  `Prepared ${modules.length} modules and About starter content: ${fileURLToPath(destination)}`
)

const migration = await readFile(
  new URL("supabase/migrations/202610110001_landing_content.sql", root),
  "utf8"
)
const setupDestination = new URL("supabase/setup.sql", root)
await writeFile(
  setupDestination,
  [
    "-- Combined landing-page schema and starter content. Run in the intended Supabase project's SQL Editor.",
    "-- Generated by npm run content:seed. Existing content rows are preserved.",
    "begin;",
    migration,
    ...inserts,
    "commit;",
    "",
  ].join("\n"),
  "utf8"
)
console.log(`Prepared one-step database setup: ${fileURLToPath(setupDestination)}`)
